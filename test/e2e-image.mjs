import { chromium } from '/opt/node22/lib/node_modules/playwright/index.mjs';
const out = process.argv[2] || '/tmp/shots';
const browser = await chromium.launch({ args: ['--use-gl=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1280, height: 820 } });
page.on('pageerror', (e) => console.log('pageerror: ' + e.message));
page.on('console', (m) => { if (m.type() === 'error') console.log('console: ' + m.text()); });
await page.goto('file://' + process.cwd() + '/dist/index.html');
const waitResult = async (prev) => {
  await page.waitForFunction((p) => { const r = window.cookiemaker?.result; return r && r.id !== p; }, prev, { timeout: 60000 });
  await page.waitForTimeout(500);
  return page.evaluate(() => { const r = window.cookiemaker.result; return { id: r.id, ok: r.ok, size: r.size.map((v) => +v.toFixed(1)), issues: r.issues.map((i) => i.level + ': ' + i.text) }; });
};
let r = await waitResult(-1);
await page.getByRole('button', { name: 'Imagen', exact: true }).click();
await page.locator('input[type=file]').setInputFiles(process.argv[3]);
await page.getByRole('button', { name: 'Usar imagen', exact: true }).click();
r = await waitResult(r.id);
console.log('image cutter', JSON.stringify(r));
await page.screenshot({ path: out + '/6-image-cutter.png' });
await page.getByRole('button', { name: 'Imprint', exact: true }).click();
r = await waitResult(r.id);
console.log('image imprint', JSON.stringify(r));
await page.getByRole('button', { name: 'Arriba', exact: true }).click();
await page.waitForTimeout(1500);
await page.screenshot({ path: out + '/7-image-imprint-top.png' });
await page.getByRole('button', { name: 'Sello', exact: true }).click();
r = await waitResult(r.id);
console.log('image stamp', JSON.stringify(r));
await page.getByRole('button', { name: 'Abajo', exact: true }).click();
await page.waitForTimeout(1500);
await page.screenshot({ path: out + '/8-image-stamp-bottom.png' });
await browser.close();
